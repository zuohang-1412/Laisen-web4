import fs from "node:fs";
import path from "node:path";
import process from "node:process";

import solc from "solc";

const repoRoot = process.cwd();
const contractsDir = path.join(repoRoot, "contracts");
const outputFile = path.join(repoRoot, "src/features/onchain/contracts/generated.ts");

const contractFiles = [
  "LaisenGovernanceToken.sol",
  "LaisenRuntimeProtocol.sol",
  "LaisenGovernor.sol",
  "LaisenTimelock.sol",
];

const sources = Object.fromEntries(
  contractFiles.map((file) => [
    file,
    {
      content: fs.readFileSync(path.join(contractsDir, file), "utf8"),
    },
  ]),
);

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: {
      enabled: true,
      runs: 200,
    },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object"],
      },
    },
  },
};

function findImports(importPath) {
  const directPath = path.join(contractsDir, importPath);
  if (fs.existsSync(directPath)) {
    return { contents: fs.readFileSync(directPath, "utf8") };
  }

  const nodeModulesPath = path.join(repoRoot, "node_modules", importPath);
  if (fs.existsSync(nodeModulesPath)) {
    return { contents: fs.readFileSync(nodeModulesPath, "utf8") };
  }

  return { error: `File not found: ${importPath}` };
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));

if (output.errors) {
  const fatalErrors = output.errors.filter((entry) => entry.severity === "error");
  if (fatalErrors.length > 0) {
    fatalErrors.forEach((entry) => {
      console.error(entry.formattedMessage);
    });
    process.exit(1);
  }
}

const contracts = [
  {
    constName: "laisenGovernanceTokenArtifact",
    sourceFile: "LaisenGovernanceToken.sol",
    contractName: "LaisenGovernanceToken",
  },
  {
    constName: "laisenRuntimeProtocolArtifact",
    sourceFile: "LaisenRuntimeProtocol.sol",
    contractName: "LaisenRuntimeProtocol",
  },
  {
    constName: "laisenGovernorArtifact",
    sourceFile: "LaisenGovernor.sol",
    contractName: "LaisenGovernor",
  },
  {
    constName: "laisenTimelockArtifact",
    sourceFile: "LaisenTimelock.sol",
    contractName: "LaisenTimelock",
  },
];

const generated = `// This file is autogenerated by scripts/compile-contracts.mjs

export const laisenGovernanceTokenArtifact = ${JSON.stringify(
  {
    abi: output.contracts["LaisenGovernanceToken.sol"].LaisenGovernanceToken.abi,
    bytecode: `0x${output.contracts["LaisenGovernanceToken.sol"].LaisenGovernanceToken.evm.bytecode.object}`,
  },
  null,
  2,
)} as const;

export const laisenRuntimeProtocolArtifact = ${JSON.stringify(
  {
    abi: output.contracts["LaisenRuntimeProtocol.sol"].LaisenRuntimeProtocol.abi,
    bytecode: `0x${output.contracts["LaisenRuntimeProtocol.sol"].LaisenRuntimeProtocol.evm.bytecode.object}`,
  },
  null,
  2,
)} as const;

export const laisenGovernorArtifact = ${JSON.stringify(
  {
    abi: output.contracts["LaisenGovernor.sol"].LaisenGovernor.abi,
    bytecode: `0x${output.contracts["LaisenGovernor.sol"].LaisenGovernor.evm.bytecode.object}`,
  },
  null,
  2,
)} as const;

export const laisenTimelockArtifact = ${JSON.stringify(
  {
    abi: output.contracts["LaisenTimelock.sol"].LaisenTimelock.abi,
    bytecode: `0x${output.contracts["LaisenTimelock.sol"].LaisenTimelock.evm.bytecode.object}`,
  },
  null,
  2,
)} as const;

export const contractArtifacts = {
${contracts.map((contract) => `  ${contract.constName},`).join("\n")}
} as const;
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, generated);

console.log(`Generated contract artifacts at ${path.relative(repoRoot, outputFile)}`);
